// Bundle the widget's TypeScript front end into the files the widget loads: ui/index.ts (and the modules it
// imports: ui + backends + static) into the one ES module of the widget, src/anywidget_vector/ui/dist/widget.js;
// and the standalone export page's renderer (ui/export.ts) into dist/export.js, which widget.py's to_html inlines
// into ui/export.html. Run after `npm ci` in the package root: npm run build. With --check it builds in memory and
// fails when a committed file differs (CI, and tests/test_ui_bundle.py).
import { build } from "esbuild";

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

import { dirname, join } from "node:path";

import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

const ui = join(here, "..", "src", "anywidget_vector", "ui");

const banner = "// Generated by scripts/build-esm.mjs from src/anywidget_vector/ui/*.ts: edit those, then npm run build";

async function bundle(entry, format) {
  const result = await build({
    entryPoints: [join(ui, entry)],
    // Inputs are named relative to this folder in the output's comments: the same file from wherever the script runs
    absWorkingDir: ui,
    bundle: true,
    format,
    // Readable output: a stack trace in a notebook points at code a person can follow
    minify: false,
    target: "es2022",
    charset: "utf8",
    legalComments: "none",
    write: false,
    logLevel: "warning",
    banner: { js: banner },
  });
  return result.outputFiles[0].text;
}

const outputs = [
  { out: join(ui, "dist", "widget.js"), text: await bundle("index.ts", "esm") },
  // The export page inlines this after its DATA/OPTIONS constants in one module script, so no exports
  { out: join(ui, "dist", "export.js"), text: await bundle("export.ts", "iife") },
];

if (process.argv.includes("--check")) {
  for (const { out, text } of outputs) {
    let committed = "";
    try {
      committed = readFileSync(out, "utf8").replaceAll("\r\n", "\n");
    } catch {
      // missing: stale
    }
    if (committed !== text) {
      console.error(`${out} is stale: run \`npm run build\` in the package root`);
      process.exit(1);
    }
    console.log(`${out} is up to date`);
  }
} else {
  mkdirSync(join(ui, "dist"), { recursive: true });
  for (const { out, text } of outputs) {
    writeFileSync(out, text);
    console.log(`wrote ${out} (${text.length} bytes)`);
  }
}
